//! Build-time extraction of the game payload from the original manager.
//!
//! `RRRE_Dedicated.exe` carries the dedicated game server as a CLR
//! `ManifestResource` named `CommunityMultiplayer.Game.game.zip`. We read the
//! CLR metadata with pure-Rust parsing, write the ZIP into `OUT_DIR`, and embed
//! it in the manager binary. At runtime the manager extracts it into its data
//! directory and launches `DedicatedServer.exe`.

use std::{collections::BTreeMap, env, fs, path::PathBuf};

use goblin::pe::{PE, options::ParseOptions};

struct EmbeddedResource {
    data: Vec<u8>,
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=METARACE_DEDICATED_EXE");

    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let input = env::var_os("METARACE_DEDICATED_EXE")
        .map(PathBuf::from)
        .unwrap_or_else(|| manifest.join("data/RRRE_Dedicated.exe"));
    println!("cargo:rerun-if-changed={}", input.display());

    let bytes = fs::read(&input).unwrap_or_else(|error| {
        panic!(
            "failed to read {}: {error}\n\
             Set METARACE_DEDICATED_EXE to the original RRRE_Dedicated.exe (or a deobfuscated rebuild) or place it at data/RRRE_Dedicated.exe before building.",
            input.display()
        )
    });
    let (assembly_major, assembly_version, resources) =
        extract_metadata(&bytes).unwrap_or_else(|error| {
            panic!(
                "cannot read .NET resources from {}: {error}",
                input.display()
            )
        });

    let game_zip = resources
        .get("CommunityMultiplayer.Game.game.zip")
        .unwrap_or_else(|| {
            panic!(
                "{} has no CommunityMultiplayer.Game.game.zip resource",
                input.display()
            )
        });

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("game.zip"), &game_zip.data).expect("write embedded game ZIP");

    let mut payload = String::new();
    payload.push_str("// Generated by build.rs from RRRE_Dedicated.exe.\n");
    payload.push_str(&format!(
        "pub const ASSEMBLY_MAJOR: u16 = {assembly_major};\n"
    ));
    payload.push_str(&format!(
        "pub const ASSEMBLY_VERSION: &str = {assembly_version:?};\n"
    ));
    payload.push_str(
        "pub static GAME_ZIP: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/game.zip\"));\n",
    );
    fs::write(out_dir.join("payload.rs"), payload).expect("write embedded payload manifest");
}

fn extract_metadata(
    data: &[u8],
) -> Result<(u16, String, BTreeMap<String, EmbeddedResource>), String> {
    let pe = PE::parse(data).map_err(|error| format!("PE parse: {error}"))?;
    let optional = pe
        .header
        .optional_header
        .as_ref()
        .ok_or_else(|| "PE has no optional header".to_string())?;
    let clr = optional
        .data_directories
        .get_clr_runtime_header()
        .ok_or_else(|| "PE has no CLR runtime header".to_string())?;
    let file_alignment = optional.windows_fields.file_alignment;
    let clr_offset = rva_to_offset(&pe, clr.virtual_address as usize, file_alignment)
        .ok_or_else(|| format!("cannot map CLR header RVA {:#x}", clr.virtual_address))?;
    let field = |offset: usize| -> Result<u32, String> {
        let end = offset
            .checked_add(4)
            .ok_or_else(|| "CLR header overflow".to_string())?;
        let bytes = data
            .get(offset..end)
            .ok_or_else(|| "truncated CLR header".to_string())?;
        Ok(u32::from_le_bytes(bytes.try_into().unwrap()))
    };

    let metadata_rva = field(clr_offset + 8)? as usize;
    let metadata_size = field(clr_offset + 12)? as usize;
    let resources_rva = field(clr_offset + 24)? as usize;
    let resources_size = field(clr_offset + 28)? as usize;

    let metadata_offset = rva_to_offset(&pe, metadata_rva, file_alignment)
        .ok_or_else(|| format!("cannot map metadata RVA {metadata_rva:#x}"))?;
    let metadata_end = metadata_offset
        .checked_add(metadata_size)
        .ok_or_else(|| "metadata size overflow".to_string())?;
    let metadata = clrmeta::Metadata::parse(
        data.get(metadata_offset..metadata_end)
            .ok_or_else(|| "truncated metadata stream".to_string())?,
    )
    .map_err(|error| format!("metadata parse: {error:?}"))?;

    let (assembly_major, assembly_version) = metadata
        .assembly()
        .map(|assembly| {
            (
                assembly.version.0,
                format!(
                    "{}.{}.{}.{}",
                    assembly.version.0, assembly.version.1, assembly.version.2, assembly.version.3
                ),
            )
        })
        .unwrap_or((112, "112.0.0.0".to_string()));

    let resources_offset = if resources_rva == 0 {
        None
    } else {
        Some(
            rva_to_offset(&pe, resources_rva, file_alignment)
                .ok_or_else(|| format!("cannot map resources RVA {resources_rva:#x}"))?,
        )
    };
    let resources_end = resources_offset.and_then(|offset| offset.checked_add(resources_size));

    let mut resources = BTreeMap::new();
    for row in &metadata.manifest_resources {
        // A zero Implementation coded index means the resource is embedded in
        // this assembly. clrmeta reports the coded index's table even for zero.
        if row.implementation.row != 0 {
            continue;
        }
        let Some(resources_offset) = resources_offset else {
            continue;
        };
        let Some(resources_end) = resources_end else {
            continue;
        };
        let offset = resources_offset
            .checked_add(row.offset as usize)
            .ok_or_else(|| "resource offset overflow".to_string())?;
        if offset + 4 > resources_end {
            continue;
        }
        let length = u32::from_le_bytes(
            data[offset..offset + 4]
                .try_into()
                .map_err(|_| "truncated resource length".to_string())?,
        ) as usize;
        let start = offset + 4;
        let end = start
            .checked_add(length)
            .ok_or_else(|| "resource length overflow".to_string())?;
        if end > resources_end {
            continue;
        }
        let name = metadata
            .strings
            .get(row.name)
            .map_err(|error| format!("resource name: {error:?}"))?
            .to_string();
        resources.insert(
            name,
            EmbeddedResource {
                data: data[start..end].to_vec(),
            },
        );
    }
    Ok((assembly_major, assembly_version, resources))
}

fn rva_to_offset(pe: &PE, rva: usize, file_alignment: u32) -> Option<usize> {
    goblin::pe::utils::find_offset(rva, &pe.sections, file_alignment, &ParseOptions::default())
}
